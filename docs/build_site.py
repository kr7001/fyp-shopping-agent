def rounded(value):
    """Floats to six places, so the file is readable and a rebuild is byte stable."""
    if isinstance(value, float):
        return round(value, 6)
    if isinstance(value, dict):
        return {k: rounded(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [rounded(v) for v in value]
    return value


def as_js(data: dict) -> str:
    body = json.dumps(data, indent=1, ensure_ascii=False, sort_keys=False)
    return ("// Generated by docs/build_site.py. Do not edit by hand: edit the source it names\n"
            "// and run `make site`.\n"
            f"window.SITE = {body};\n")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="compare against docs/site-data.js instead of writing it")
    args = parser.parse_args()
    data = rounded(build())
    if args.check:
        if not OUT.exists():
            print("docs/site-data.js does not exist. Run `make site`.")
            return 1
        current = json.loads(OUT.read_text().split("window.SITE = ", 1)[1].rstrip().rstrip(";"))
        current.pop("built", None)
        if current != json.loads(json.dumps(data)):
            stale = sorted(k for k in data if current.get(k) != json.loads(json.dumps(data[k])))
            print(f"docs/site-data.js is stale in: {', '.join(stale)}. Run `make site`.")
            return 1
        print("docs/site-data.js matches its sources")
        return 0
    data["built"] = built()
    OUT.write_text(as_js(data))
    print(f"wrote {OUT.relative_to(REPO)}, {OUT.stat().st_size // 1024} KB, at commit "
          f"{data['built']['commit']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
