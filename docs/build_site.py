def unit_tests() -> list[dict]:
    files = []
    for path in sorted((paths.EXPERIMENTS / "tests").glob("test_*.py")):
        tree = ast.parse(path.read_text())
        classes = []
        for node in tree.body:
            if isinstance(node, ast.ClassDef):
                tests = [fn.name[5:].replace("_", " ") for fn in node.body
                         if isinstance(fn, ast.FunctionDef) and fn.name.startswith("test_")]
                classes.append({"name": node.name,
                                "doc": (ast.get_docstring(node) or "").split("\n\n")[0],
                                "tests": tests})
        files.append({"file": str(path.relative_to(REPO)),
                      "doc": " ".join((ast.get_docstring(tree) or "").split("\n\n")[0].split()),
                      "classes": classes})
    return files


def mod_tests() -> list[str]:
    text = (REPO / "tools/workbench/igr-workbench/tests/workbench.test.ts").read_text()
    return re.findall(r"^test\('([^']+)'", text, re.MULTILINE)


def excerpt(file: str, start: str, end: str, extra: int) -> dict:
    lines = (REPO / file).read_text().splitlines()
    first = next((i for i, line in enumerate(lines) if start in line), None)
    if first is None:
        raise SystemExit(f"excerpt anchor not found in {file}: {start!r}")
    last = next((i for i in range(first, len(lines)) if end in lines[i]), None)
    if last is None or last - first > 80:
        raise SystemExit(f"excerpt end not found within 80 lines in {file}: {end!r}")
    last = min(len(lines) - 1, last + extra)
    return {"file": file, "start": first + 1, "end": last + 1,
            "code": "\n".join(lines[first:last + 1])}


def code() -> dict:
    return {key: excerpt(file, start, end, extra) for key, file, start, end, extra in EXCERPTS}


