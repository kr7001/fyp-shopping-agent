def lessons() -> dict:
    lead, found = split_sections((REPO / "LESSONS.md").read_text())
    groups = []
    for title, body in found:
        rows = []
        for line in body.splitlines():
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if len(cells) == 4 and cells[0].isdigit():
                rows.append({"n": int(cells[0]), "what": inline(cells[1]),
                             "rule": inline(cells[2]),
                             "who": [w.strip() for w in cells[3].split(",")]})
        groups.append({"group": title, "rows": rows})
    return {"intro": render(lead), "groups": groups}


def parked() -> list[dict]:
    found = []
    for line in (REPO / "PARKED.md").read_text().splitlines():
        m = re.match(r"^-\s+(\d{4}-\d\d-\d\d):\s+(.*)", line.strip())
        if m:
            found.append({"date": m.group(1), "text": inline(m.group(2))})
    return found


def ledger() -> list[dict]:
    """The market ledger table in README.md, the one record of what each market may test."""
    text = (REPO / "README.md").read_text()
    part = text.split("## Market ledger", 1)[1].split("\n## ", 1)[0].split("\n### ", 1)[0]
    rows = []
    for line in part.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 4 and line.startswith("|") and not set(cells[0]) <= set("- ") \
                and cells[0] != "Market":
            rows.append({"market": inline(cells[0]), "listings": cells[1],
                         "status": inline(cells[2]), "use": inline(cells[3])})
    return rows


