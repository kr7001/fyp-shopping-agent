    for name, how in TASK_FILES.items():
        spec = json.loads((paths.TASKS / name).read_text())
        tasks.append({"file": name, "how": how, "questions": len(spec["tasks"]),
                      "gated": sum(1 for t in spec["tasks"] if t.get("gated"))})
    return {"markets": markets, "tasks": tasks, "ledger": ledger()}


