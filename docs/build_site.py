def describe_answer(expect: dict) -> str:
    kind = expect["kind"]
    if kind == "price":
        return f"${expect['value']:.2f}"
    if kind == "count":
        return str(expect["value"])
    if kind == "boolean":
        return "Yes" if expect["value"] else "No"
    if kind == "contains":
        price = f" at ${expect['price']:.2f}" if expect.get("price") is not None else ""
        return " or ".join(expect["any"]) + price
    return json.dumps(expect)


