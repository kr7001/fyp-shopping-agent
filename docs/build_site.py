def water() -> list[dict]:
    groups: dict[tuple, list[tuple[str, dict]]] = collections.defaultdict(list)
    for suite_path in sorted(paths.RESULTS.glob("*/suite.json")):
        batch = suite_path.parent.name
        payload = json.loads(suite_path.read_text())
        if batch in VOID or payload.get("superseded"):
            continue
        rows = [r for r in payload["rows"] if r["task"] in arms.GATED]
        if not rows:
            continue
        record = first_record(suite_path.parent)
        key = (payload.get("draw"), arms.arm_name(payload), model_of(payload, record),
               scaffold_of(payload, record))
        groups[key].extend((batch, r) for r in rows)
    out = []
    for market, draw, arm, label in WATER_ARMS:
        found = groups.get((draw, arm, HAIKU, "openjiuwen"), [])
        rows = [r for _, r in found]
        verdicts = collections.Counter(r["verdict"] for r in rows)
        actions = [r["actions"] for r in rows if r.get("actions") is not None]
        costs = [r["cost_usd"] for r in rows if r.get("cost_usd") is not None]
        out.append({"market": market, "arm": label, "arm_name": arm, "draw": draw,
                    "batches": sorted({b for b, _ in found}), "runs": len(rows),
                    "correct": verdicts["correct"], "refused": verdicts["abstained"],
                    "other": len(rows) - verdicts["correct"] - verdicts["abstained"],
                    "actions": round(statistics.mean(actions), 2) if actions else None,
                    "cost": round(statistics.mean(costs), 4) if costs else None})
    return out


