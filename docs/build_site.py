def git(*args: str) -> str:
    return subprocess.run(["git", *args], cwd=REPO, capture_output=True, text=True).stdout.strip()


def built() -> dict:
    """Facts about the checkout rather than the research, left out of --check.

    Code excerpts link to GitHub at the commit built from, or to the branch when the
    checkout had changes beyond this file, since their lines may not exist at that commit.
    """
    counts = collections.Counter()
    for day in git("log", "--format=%ad", "--date=short").split():
        date = dt.date.fromisoformat(day)
        counts[(date - dt.timedelta(days=date.weekday())).isoformat()] += 1
    remote = git("remote", "get-url", "origin")
    repo = re.sub(r"^git@github\.com:|^https://github\.com/", "", remote).removesuffix(".git")
    # The submodule always carries the local patch, so it never counts as a change here.
    dirty = [line for line in git("status", "--porcelain", "--ignore-submodules").splitlines()
             if not line.endswith("docs/site-data.js")]
    return {"commit": git("rev-parse", "--short", "HEAD"), "date": dt.date.today().isoformat(),
            "branch": git("branch", "--show-current"), "dirty": bool(dirty),
            "repo": f"https://github.com/{repo}" if repo else "",
            "agent_core": git("ls-files", "-s", "agent/agent-core").split()[1][:40],
            "commits_by_week": dict(sorted(counts.items()))}


def week_start(title: str) -> str | None:
    m = re.match(r"Week of (\d{1,2}) (\w+)", title)
    if not m:
        return None
    return dt.datetime.strptime(f"{m.group(1)} {m.group(2)} {YEAR}", "%d %B %Y").date().isoformat()


