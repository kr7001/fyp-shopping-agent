# ------------------------------------------------------------------- markdown, a small subset

def inline(text: str) -> str:
    """Code, bold, italics and links, on text escaped first."""
    out = html.escape(text, quote=False)
    out = re.sub(r"`([^`]+)`", r"<code>\1</code>", out)
    out = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", out)
    out = re.sub(r"(?<![*\w])\*([^*\s][^*]*)\*(?![*\w])", r"<em>\1</em>", out)
    out = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", r'<a href="\2">\1</a>', out)
    return out


def render(md: str) -> str:
    """Paragraphs, bullet and numbered lists, and ### headings. Enough for these files."""
    out: list[str] = []
    para: list[str] = []
    items: list[str] = []
    kind = ""

    def end_para():
        if para:
            out.append(f"<p>{inline(' '.join(para))}</p>")
            para.clear()

    def end_list():
        nonlocal kind
        if items:
            tag = "ol" if kind == "ol" else "ul"
            out.append(f"<{tag}>" + "".join(f"<li>{inline(i)}</li>" for i in items) + f"</{tag}>")
            items.clear()
        kind = ""

    for line in md.splitlines():
        text = line.strip()
        if not text:
            end_para()
            end_list()
            continue
        heading = re.match(r"^(#{3,4})\s+(.*)", text)
        bullet = re.match(r"^[-*]\s+(.*)", text)
        number = re.match(r"^\d+\.\s+(.*)", text)
        if heading:
            end_para()
            end_list()
            out.append(f"<h4>{inline(heading.group(2))}</h4>")
        elif bullet or number:
            end_para()
            want = "ul" if bullet else "ol"
            if kind and kind != want:
                end_list()
            kind = want
            items.append((bullet or number).group(1))
        elif items and line.startswith("  "):
            items[-1] += " " + text
        else:
            end_list()
            para.append(text)
    end_para()
    end_list()
    return "\n".join(out)


def split_sections(md: str) -> tuple[str, list[tuple[str, str]]]:
    """The text before the first `## ` heading, and every `## ` section after it."""
    lead, found, title, body = [], [], None, []
    for line in md.splitlines():
        if line.startswith("# "):
            continue
        if line.startswith("## "):
            if title is not None:
                found.append((title, "\n".join(body)))
            title, body = line[3:].strip(), []
        elif title is None:
            lead.append(line)
        else:
            body.append(line)
    if title is not None:
        found.append((title, "\n".join(body)))
    return "\n".join(lead), found


def content(name: str) -> dict:
    lead, found = split_sections((CONTENT / f"{name}.md").read_text())
    return {"intro": render(lead),
            "sections": [{"title": t, "html": render(b)} for t, b in found]}


