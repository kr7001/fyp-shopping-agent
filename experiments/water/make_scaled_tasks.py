#!/usr/bin/env python3
"""Derive the scaled task suite from the generated catalogue.

Ground truth is computed from the fixture rather than written by hand. Fifteen listings
carry roughly sixty prices, and every derived answer written out by a person is a chance
for the answer key to disagree with the shop. Regenerating the catalogue regenerates
these tasks, so the two cannot drift apart.

Tasks are posed over the search page rather than named URLs. That is the whole point of
scaling: the RQ2 cross-listing task scored 5/5 precisely because both addresses were
handed over, making the comparison cheap. Here the agent has to decide which of fifteen
results are worth opening.

    python experiments/water/make_scaled_tasks.py
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import paths  # noqa: E402

FIXTURE = paths.FIXTURES / "scaled_water.json"
OUT = paths.TASKS / "tasks_scaled.json"
SEARCH = "{base}/catalogsearch/result/?q=Rivenhall"


def first_name(seller: str) -> str:
    """The distinguishing half of a trading name, which the generator keeps unique."""
    return seller.split()[0]


def build(fixture: dict) -> dict:
    families = fixture["families"]
    facts = fixture["_instance"]
    target = facts["target_option"]
    winner_seller = facts["winner"]["seller"]
    winner_price = facts["winner"]["price"]
    card_seller = facts["cheapest_card"]["seller"]

    # Taken from the generator's own facts rather than recomputed here. Two
    # implementations of the same sum are two chances to disagree, and the generator
    # already enforces that this seller differs from both other answers.
    unit_seller = facts["best_per_litre"]["seller"]

    missing = [f["seller"] for f in families
               if not any(v["option"] == target for v in f["variants"])]

    return {
        "_about": [
            "Generated by experiments/make_scaled_tasks.py from scaled_water.json.",
            "Do not hand edit. Regenerate after regenerating the catalogue.",
            f"Catalogue seed {fixture['_generated']['seed']}, "
            f"{facts['listings']} listings, exhaustive {facts['exhaustive_opens']} opens, "
            f"oracle floor {facts['oracle_min_opens']} opens.",
        ],
        "_instance": facts,
        "base_url": "http://localhost:7770",
        "tasks": [
            {
                "id": "scaled-headline",
                "family": "scaled",
                "gated": False,
                "note": ("Control. The answer is on the search page itself, so a card level "
                         "probe should settle it in one or two actions. If this fails, the "
                         "agent cannot read the search page at all and the gated results "
                         "below mean nothing."),
                "query": ("Go to " + SEARCH + " . Of the Rivenhall water listings shown, "
                          "which one advertises the lowest price on the results page, and "
                          "what is that price?"),
                "expect": {"kind": "contains", "any": [first_name(card_seller)],
                           "price": facts["cheapest_card"]["from_price"]},
            },
            {
                "id": "scaled-cheapest-target",
                "family": "scaled",
                "gated": True,
                "note": ("The headline task. The lowest advertised price belongs to "
                         f"{card_seller}, but the cheapest {target} is {winner_seller}. "
                         "Answering from the search page alone gives the wrong seller."),
                "query": ("Go to " + SEARCH + f" . Across all the Rivenhall listings, which "
                          f"seller is cheapest for the {target} pack, and what is that price?"),
                "expect": {"kind": "contains", "any": [first_name(winner_seller)],
                           "not_any": [first_name(card_seller)], "price": winner_price},
            },
            {
                "id": "scaled-target-price",
                "family": "scaled",
                "gated": True,
                "note": "Same retrieval, scored on the number rather than the seller name.",
                "query": ("Go to " + SEARCH + f" . What is the lowest price anyone charges "
                          f"for the {target} pack of Rivenhall water?"),
                "expect": {"kind": "price", "value": winner_price,
                           "trap": facts["cheapest_card"]["from_price"]},
            },
            {
                "id": "scaled-all-stocked",
                "family": "scaled",
                "gated": True,
                "note": (f"{len(missing)} of {facts['listings']} listings do not stock the "
                         "target at all. Answering yes means the agent assumed every search "
                         "result was comparable without checking."),
                "query": ("Go to " + SEARCH + f" . Does every Rivenhall listing stock the "
                          f"{target} pack? Answer yes or no."),
                "expect": {"kind": "boolean", "value": False},
            },
            {
                "id": "scaled-best-per-litre",
                "family": "scaled",
                "gated": True,
                "note": ("Needs every variant of every listing, so it is the most expensive "
                         "question in the suite and the clearest test of whether the agent "
                         "budgets its retrieval or simply gives up."),
                "query": ("Go to " + SEARCH + " . Across all the Rivenhall listings and all "
                          "their pack sizes, which seller offers the lowest price per litre?"),
                "expect": {"kind": "contains", "any": [first_name(unit_seller)]},
            },
        ],
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--fixture", type=pathlib.Path, default=FIXTURE)
    parser.add_argument("--out", type=pathlib.Path, default=OUT)
    args = parser.parse_args()

    fixture = json.loads(args.fixture.read_text())
    spec = build(fixture)
    brand = (fixture.get("_generated") or {}).get("brand", "Rivenhall")
    if brand != "Rivenhall":
        for task in spec["tasks"]:
            task["query"] = task["query"].replace("Rivenhall", brand)
        spec["brand"] = brand
    args.out.write_text(json.dumps(spec, indent=2) + "\n")

    facts = spec["_instance"]
    print(f"{len(spec['tasks'])} tasks written to {args.out}")
    print(f"  winner        {facts['winner']['seller']} at ${facts['winner']['price']}")
    print(f"  card probe    {facts['cheapest_card']['seller']} at "
          f"${facts['cheapest_card']['from_price']}")
    print(f"  exhaustive    {facts['exhaustive_opens']} opens")
    print(f"  oracle floor  {facts['oracle_min_opens']} opens")
    for task in spec["tasks"]:
        print(f"  {task['id']:24} gated={str(task['gated']):5} {task['expect']['kind']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
